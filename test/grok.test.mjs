test('extractSection and replaceSection respect heading levels and code fences', () => {
  const doc = '# T\n\n## A\n\nbody a\n\n```\n## not a heading\n```\n\n### A1\n\nsub\n\n## B\n\nbody b\n';
  assert.equal(extractSection(doc, '## A'), '## A\n\nbody a\n\n```\n## not a heading\n```\n\n### A1\n\nsub');
  assert.equal(extractSection(doc, '### A1'), '### A1\n\nsub');
  assert.ok(replaceSection(doc, '## A', '## A\n\nnew').includes('## A\n\nnew\n\n## B'));
  assert.throws(() => extractSection(doc, '## Missing'), /heading not found/);
});

test('renderApprovals keeps comments and applies overrides', () => {
  const text = 'version: 1\nactions:\n  read_inbox: auto\n  preview_leads: auto  # free\n  send_reply: ask\n  delete_anything: never\n';
  const out = renderApprovals(text, { read_inbox: 'look at the inbox' });
  assert.match(out, /- `read_inbox`: look at the inbox/);
  assert.match(out, /- `preview_leads`: free/);
  assert.ok(out.indexOf('(ask)') < out.indexOf('send_reply') && out.indexOf('send_reply') < out.indexOf('(never)'));
});
